"""Create a self-contained local runner bundle: PKI, catalog, policy, env file.

Nothing here is a production credential: the bundle is generated on demand,
lives in a private directory and is safe to delete.  It exists so a developer
or a test can start the real runner worker with mutual TLS in one step.

    PYTHONPATH=apps/api python scripts/runner-dev-bootstrap.py .runner-dev
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

EXERCISE_MODULE = "app.runner_exercise_content"


def openssl(*args: str) -> None:
    result = subprocess.run(["openssl", *args], capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f"openssl {' '.join(args)} failed: {result.stderr.strip()}")


def write_extensions(path: Path, *, san: str) -> None:
    path.write_text(
        "basicConstraints=critical,CA:FALSE\n"
        "keyUsage=critical,digitalSignature,keyEncipherment\n"
        "extendedKeyUsage=serverAuth,clientAuth\n"
        f"subjectAltName={san}\n",
        encoding="utf-8",
    )


def main() -> None:
    target = Path(sys.argv[1] if len(sys.argv) > 1 else ".runner-dev").resolve()
    if shutil.which("openssl") is None:
        raise SystemExit("openssl is required")
    target.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(target, 0o700)

    openssl("req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "2",
            "-keyout", str(target / "ca.key"), "-out", str(target / "ca.pem"),
            "-subj", "/CN=ai-tutor-local-client-ca",
            "-addext", "basicConstraints=critical,CA:TRUE",
            "-addext", "keyUsage=critical,keyCertSign,cRLSign")
    # `runner` is the compose service name the API dials; the extras cover a
    # host-specific name without regenerating the whole bundle.
    extra = os.getenv("RUNNER_EXTRA_DNS_SANS", "").strip()
    server_san = "URI:spiffe://ai-tutor/runner,DNS:localhost,DNS:runner,IP:127.0.0.1"
    if extra:
        server_san += "," + ",".join(f"DNS:{name}" for name in extra.split(",") if name.strip())
    for name, san in (("server", server_san),
                      ("client", "URI:spiffe://ai-tutor/api")):
        openssl("req", "-newkey", "rsa:2048", "-nodes",
                "-keyout", str(target / f"{name}.key"), "-out", str(target / f"{name}.csr"),
                "-subj", f"/CN=ai-tutor-{name}")
        extensions = target / f"{name}.ext"
        write_extensions(extensions, san=san)
        openssl("x509", "-req", "-in", str(target / f"{name}.csr"), "-CA", str(target / "ca.pem"),
                "-CAkey", str(target / "ca.key"), "-CAcreateserial", "-days", "2",
                "-out", str(target / f"{name}.pem"), "-extfile", str(extensions))
        (target / f"{name}.csr").unlink()
        extensions.unlink()
    for path in target.glob("*.key"):
        os.chmod(path, 0o600)

    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "apps" / "api"))
    module = __import__(EXERCISE_MODULE, fromlist=["RUNNER_EXERCISES"])
    rows = [{"exercise_id": row["exercise_id"], "version": row["version"],
             "cases": [{key: case[key] for key in ("args", "kwargs", "expected", "visibility")}
                       for case in row["cases"]]}
            for row in module.RUNNER_EXERCISES.values()]
    catalog = target / "catalog.json"
    catalog.write_text(json.dumps(rows, ensure_ascii=False, allow_nan=False, separators=(",", ":")),
                       encoding="utf-8")
    os.chmod(catalog, 0o600)

    policy = target / "policy.json"
    policy.write_text(json.dumps({"policy": "python-authored-v1", "isolation_verified": True}),
                      encoding="utf-8")

    token = os.urandom(32).hex()
    state = target / "state"
    state.mkdir(mode=0o700, exist_ok=True)
    env_file = target / "env.sh"
    env_file.write_text(
        "# Generated by scripts/runner-dev-bootstrap.py — local development only.\n"
        f"export RUNNER_STATE_DIR={state}\n"
        f"export RUNNER_CATALOG_FILE={catalog}\n"
        f"export RUNNER_HOST_ATTESTATION_FILE={target / 'host-attestation.json'}\n"
        "export RUNNER_SANDBOX_BACKEND=${RUNNER_SANDBOX_BACKEND:-auto}\n"
        "export RUNNER_BIND=127.0.0.1\n"
        "export RUNNER_PORT=8443\n"
        "export RUNNER_ALLOWED_API_IDENTITIES=spiffe://ai-tutor/api\n"
        f"export RUNNER_AUTH_TOKEN={token}\n"
        f"export RUNNER_CLIENT_CA_FILE={target / 'ca.pem'}\n"
        f"export RUNNER_SERVER_CERT_FILE={target / 'server.pem'}\n"
        f"export RUNNER_SERVER_KEY_FILE={target / 'server.key'}\n"
        f"export RUNNER_URL=https://127.0.0.1:8443/internal/v1/runner/executions\n"
        f"export RUNNER_CA_FILE={target / 'ca.pem'}\n"
        f"export RUNNER_CLIENT_CERT_FILE={target / 'client.pem'}\n"
        f"export RUNNER_CLIENT_KEY_FILE={target / 'client.key'}\n"
        f"export RUNNER_VERIFIED_POLICY_FILE={policy}\n",
        encoding="utf-8",
    )
    os.chmod(env_file, 0o600)
    print(f"bundle ready: {target}")
    print(f"exercises: {len(rows)}")
    print(f"source {env_file}")


if __name__ == "__main__":
    main()
