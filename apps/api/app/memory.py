"""Structured memory: a summary of the dialogue and a behavioural profile.

The mentor gets a bounded, structured summary instead of a transcript: how many
questions were asked, which terms keep coming back, whether the last question is
still unanswered, and how the learner actually behaves (which mode they pick, how
often runs pass). Nothing here stores code, and nothing is generated by a model —
these are counts over facts the product already recorded.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import UTC, datetime, timedelta
from uuid import UUID

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.db.models import CodingAttempt, LessonCompletion, MentorConversation, MentorMessage, User

STOPWORDS = {"что", "как", "это", "для", "или", "мне", "меня", "если", "чтобы", "почему", "где", "есть",
             "не", "на", "в", "с", "и", "а", "о", "у", "я", "ты", "мы", "вы", "the", "a", "is", "to", "of"}
MAX_TOPICS = 5
MAX_QUESTION_CHARS = 160


@dataclass(frozen=True)
class InteractionSummary:
    lesson_id: str
    questions: int
    answers: int
    topics: list[str] = field(default_factory=list)
    last_question: str | None = None
    last_question_at: datetime | None = None
    awaiting_answer: bool = False

    def as_dict(self) -> dict:
        return {
            "lesson_id": self.lesson_id,
            "questions": self.questions,
            "answers": self.answers,
            "topics": list(self.topics),
            "last_question": self.last_question,
            "last_question_at": self.last_question_at.isoformat() if self.last_question_at else None,
            "awaiting_answer": self.awaiting_answer,
        }

    def prompt_block(self) -> str:
        """Bounded text for the mentor prompt; treated as untrusted data."""
        parts = [f"asked={self.questions}", f"answered={self.answers}"]
        if self.topics:
            parts.append("recurring_terms=" + ",".join(self.topics))
        if self.awaiting_answer:
            parts.append("last_question_unanswered")
        return "previous_dialogue: " + "; ".join(parts)


def _topics(texts: list[str]) -> list[str]:
    frequency: dict[str, int] = {}
    for text in texts:
        for word in re.findall(r"[a-zа-яё]{4,}", text.casefold()):
            if word in STOPWORDS:
                continue
            frequency[word] = frequency.get(word, 0) + 1
    ranked = sorted(frequency.items(), key=lambda item: (-item[1], item[0]))
    return [word for word, count in ranked[:MAX_TOPICS] if count > 1] or [word for word, _ in ranked[:MAX_TOPICS]]


def interaction_summary(db: Session, *, user_id: UUID, lesson_id: str) -> InteractionSummary:
    conversation = db.scalar(
        select(MentorConversation).where(MentorConversation.user_id == user_id,
                                         MentorConversation.lesson_id == lesson_id)
    )
    if conversation is None:
        return InteractionSummary(lesson_id=lesson_id, questions=0, answers=0)
    messages = list(db.scalars(
        select(MentorMessage)
        .where(MentorMessage.conversation_id == conversation.id, MentorMessage.status == "completed")
        .order_by(MentorMessage.created_at.desc())
        .limit(20)
    ))
    questions = [message for message in messages if message.role == "user"]
    answers = [message for message in messages if message.role == "assistant"]
    last_question = questions[0] if questions else None
    awaiting = bool(last_question) and (not messages or messages[0].id == last_question.id)
    return InteractionSummary(
        lesson_id=lesson_id,
        questions=len(questions),
        answers=len(answers),
        topics=_topics([message.content for message in questions][:10]),
        last_question=(last_question.content[:MAX_QUESTION_CHARS] if last_question else None),
        last_question_at=last_question.created_at if last_question else None,
        awaiting_answer=awaiting,
    )


def behavioural_profile(db: Session, *, user: User, now: datetime | None = None) -> dict:
    now = now or datetime.now(UTC)
    modes = dict(
        db.execute(
            select(MentorMessage.mode, func.count())
            .join(MentorConversation, MentorConversation.id == MentorMessage.conversation_id)
            .where(MentorConversation.user_id == user.id, MentorMessage.mode.is_not(None))
            .group_by(MentorMessage.mode)
        ).all()
    )
    preferred_mode = max(modes.items(), key=lambda item: item[1])[0] if modes else None
    runs = dict(
        db.execute(
            select(CodingAttempt.status, func.count())
            .where(CodingAttempt.user_id == user.id)
            .group_by(CodingAttempt.status)
        ).all()
    )
    finished = runs.get("passed", 0) + runs.get("failed", 0)
    pass_rate = round(runs.get("passed", 0) / finished, 3) if finished else 0.0
    lessons_30 = db.scalar(
        select(func.count()).select_from(LessonCompletion).where(
            LessonCompletion.user_id == user.id,
            LessonCompletion.completed_at >= now - timedelta(days=30),
        )
    ) or 0
    return {
        "preferred_tutor_mode": preferred_mode,
        "mode_usage": modes,
        "coding_runs": finished,
        "coding_pass_rate": pass_rate,
        "lessons_last_30_days": int(lessons_30),
        "pace": "steady" if lessons_30 >= 4 else ("slow" if lessons_30 else "inactive"),
    }
