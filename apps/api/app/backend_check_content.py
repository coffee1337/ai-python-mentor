from typing import Final


def _check(
    *,
    question_id: str,
    prompt: str,
    choices: tuple[str, ...],
    answer: str,
    explanation: str,
    choice_explanations: dict[str, str],
) -> dict:
    if answer not in choices:
        raise ValueError(f"{question_id}: the answer must be one of the choices")
    if set(choice_explanations) != set(choices):
        raise ValueError(f"{question_id}: every choice needs an explanation")
    return {
        "id": question_id,
        "prompt": prompt,
        "choices": list(choices),
        "answer": answer,
        "explanation": explanation,
        "choice_explanations": dict(choice_explanations),
    }


