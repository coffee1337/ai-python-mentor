def _check(question_id, prompt, correct, distractors, explanations):
    choices = [correct, *distractors]
    return {"id": question_id, "prompt": prompt, "choices": choices,
            "answer": correct, "explanation": explanations[0],
            "choice_explanations": dict(zip(choices, explanations, strict=True))}


