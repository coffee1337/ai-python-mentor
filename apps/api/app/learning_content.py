_HINT_KINDS = ("direction", "concept", "step", "pseudocode", "solution")
_LEAKAGE_MARKERS = ("решение", "правильный ответ", "ответ:", "solution", "correct answer")


def validate_hint_ladders() -> None:
    """Reject malformed authored ladders before they can be persisted."""
    lesson_by_id = {lesson["id"]: lesson for lesson in LESSONS}
    for exercise_id, ladder in EXERCISE_HINT_LADDERS.items():
        lesson = lesson_by_id.get(exercise_id)
        if lesson is None or ladder["lesson_id"] != exercise_id:
            raise ValueError("Hint ladder references an unknown lesson")
        hints = tuple(ladder["hints"])
        if ladder["version"] < 1 or len(hints) != 5:
            raise ValueError("Hint ladder must contain exactly five levels")
        for expected_level, (level, kind, text) in enumerate(hints, start=1):
            if level != expected_level or kind != _HINT_KINDS[expected_level - 1]:
                raise ValueError("Hint levels and kinds must be ordered")
            if not 1 <= len(text) <= 2000:
                raise ValueError("Hint text length is out of bounds")
            normalized = text.casefold()
            if expected_level < 5:
                if any(marker in normalized for marker in _LEAKAGE_MARKERS):
                    raise ValueError("Non-solution hint contains a solution marker")
                if lesson["answer"].casefold() in normalized:
                    raise ValueError("Non-solution hint contains the answer")


validate_hint_ladders()
