import data from "../../content/seo.json";

export type Concept = {
  slug: string;
  title: string;
  skill_id: string;
  skill: string;
  phase: string;
  summary: string;
  body: string;
  minutes: number;
  difficulty: string | number;
};

export type SkillPage = {
  id: string;
  slug: string;
  name: string;
  category: string;
  description: string;
  lessons: { slug: string; title: string }[];
};

export type Roadmap = {
  slug: string;
  title: string;
  outcome: string;
  minutes: number;
  lessons: { slug: string; title: string; minutes: number }[];
};

export type ErrorPage = {
  slug: string;
  title: string;
  lesson: string;
  lesson_slug: string;
  misconception: string;
  correction: string;
};

export const concepts: Concept[] = data.concepts;
export const skills: SkillPage[] = data.skills;
export const roadmaps: Roadmap[] = data.roadmaps;
export const errors: ErrorPage[] = data.errors;

export const SITE = process.env.NEXT_PUBLIC_SITE_URL || "https://mentor.example.com";

export function concept(slug: string): Concept | undefined {
  return concepts.find((item) => item.slug === slug);
}

export function skill(slug: string): SkillPage | undefined {
  return skills.find((item) => item.slug === slug);
}

export function roadmap(slug: string): Roadmap | undefined {
  return roadmaps.find((item) => item.slug === slug);
}

export function errorPage(slug: string): ErrorPage | undefined {
  return errors.find((item) => item.slug === slug);
}

